import { BadRequestException, ConflictException, HttpStatus, Injectable, Logger, NotFoundException } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { apiError } from '../../common/errors.js';
import type { Env } from '../../config/env.js';
import type { MediaJob, Prisma, User } from '../../generated/prisma/client.js';
import { MotionStudio, type MotionRequest } from '../../integrations/media/motion/motion-studio.js';
import { MOTION_SET } from '../../integrations/media/motion/templates/index.js';
import { FileStorage } from '../../integrations/supabase/file-storage.js';
import { PrismaService } from '../../prisma/prisma.service.js';
import type { MotionDto, RedoVariantDto } from './dto/video.dto.js';
import { motionDefaults } from './motion-words.js';
import { findMyPiece } from './studio-pieces.js';
import { toView } from './studio-video.service.js';

type VariantStatus = 'QUEUED' | 'RUNNING' | 'DONE' | 'FAILED';
export interface MotionVariant {
  key: string;
  template: string;
  name: string;
  description: string;
  status: VariantStatus;
  storyboardUrl: string | null;
  outputUrl: string | null;
  error: string | null;
  /** Words used for this variation when it was redone with new ones. */
  words?: string[];
}
interface MotionOptions {
  words: string[];
  cta: string | null;
  handle: string | null;
  businessName: string;
  logoUrl: string | null;
  picked?: string;
}

const RUNNING_FOR_MS = 15 * 60 * 1000;
const FRIENDLY = "Couldn't make this moving ad. Please try again.";

/**
 * Moving ads ("Make it move"): 3 motion design variations from a real photo,
 * storyboards first, then videos (cebi-studio skill, "Three variations").
 * Nothing is generated by AI, so the label is "Edited". Runs in the API
 * process like the other media jobs.
 */
@Injectable()
export class StudioMotionService {
  private readonly logger = new Logger('StudioMotion');
  private readonly debug: boolean;

  constructor(
    private readonly prisma: PrismaService,
    private readonly storage: FileStorage,
    private readonly motion: MotionStudio,
    config: ConfigService<Env, true>,
  ) {
    this.debug = config.get('NODE_ENV', { infer: true }) === 'development';
  }

  async start(creator: User, dto: MotionDto) {
    const piece = await findMyPiece(this.prisma, creator, dto.pieceId);
    const ownPhoto = dto.imageUrl.includes(`/enhance/${creator.id}/`) || dto.imageUrl.includes(`/pieces/${piece.id}/`);
    if (!this.storage.isOurs(dto.imageUrl) || !ownPhoto) {
      throw new BadRequestException(['imageUrl must be a photo you added or enhanced in Cebi']);
    }
    const words = dto.words.map((w) => w.trim().replace(/\s+/g, ' ')).filter(Boolean);
    if (!words.length) throw new BadRequestException(['words must have at least one word']);
    const defaults = motionDefaults(piece.campaign);
    // The end card only repeats what the brief says (its code, link or hashtags).
    if (dto.cta && !defaults.ctaOptions.includes(dto.cta)) {
      throw new BadRequestException(["cta must be the brief's promo code, link or one of its hashtags"]);
    }
    // Rendering is heavy: one moving ad at a time per person.
    const busy = await this.prisma.mediaJob.findFirst({
      where: { userId: creator.id, kind: 'MOTION', status: { in: ['QUEUED', 'RUNNING'] }, updatedAt: { gt: new Date(Date.now() - RUNNING_FOR_MS) } },
    });
    if (busy) throw apiError(HttpStatus.CONFLICT, 'MOTION_BUSY', 'Your moving ads are still being made. Try again when they are ready.');

    const options: MotionOptions = {
      words,
      cta: dto.cta ?? null,
      handle: defaults.handle,
      businessName: defaults.businessName,
      logoUrl: piece.campaign.business.businessProfile?.logoUrl ?? null,
    };
    const variants: MotionVariant[] = MOTION_SET.map((v) => ({ ...v, status: 'QUEUED', storyboardUrl: null, outputUrl: null, error: null }));
    const job = await this.prisma.mediaJob.create({
      data: {
        userId: creator.id,
        pieceId: piece.id,
        kind: 'MOTION',
        inputUrl: dto.imageUrl,
        options: options as unknown as Prisma.InputJsonValue,
        variants: variants as unknown as Prisma.InputJsonValue,
      },
    });
    this.run(job, variants.map((v) => v.key));
    return toView(job);
  }

  /** Keeps one variation (the one sent to the business). */
  async pick(user: User, jobId: string, key: string) {
    const job = await this.myJob(user, jobId);
    const variant = this.variants(job).find((v) => v.key === key);
    if (variant?.status !== 'DONE') throw new BadRequestException(['That variation is not ready']);
    const updated = await this.prisma.mediaJob.update({
      where: { id: job.id },
      data: { options: { ...(job.options as object), picked: key } as Prisma.InputJsonValue },
    });
    return toView(updated);
  }

  /** Makes one variation again, with new words if given. */
  async redo(user: User, jobId: string, dto: RedoVariantDto) {
    const job = await this.myJob(user, jobId);
    if (job.status === 'QUEUED' || job.status === 'RUNNING') {
      throw new ConflictException('Wait until these moving ads are ready.');
    }
    const words = dto.words?.map((w) => w.trim()).filter(Boolean);
    const variants = this.variants(job).map((v) =>
      v.key === dto.key ? { ...v, status: 'QUEUED' as const, error: null, ...(words?.length && { words }) } : v,
    );
    if (!variants.some((v) => v.key === dto.key)) throw new NotFoundException('Not found');
    const updated = await this.prisma.mediaJob.update({
      where: { id: job.id },
      data: { status: 'RUNNING', error: null, variants: variants as unknown as Prisma.InputJsonValue },
    });
    this.run(updated, [dto.key]);
    return toView(updated);
  }

  private async myJob(user: User, id: string) {
    const job = await this.prisma.mediaJob.findFirst({ where: { id, userId: user.id, kind: 'MOTION' } });
    if (!job) throw new NotFoundException('Not found');
    return job;
  }

  private variants(job: MediaJob) {
    return (job.variants ?? []) as unknown as MotionVariant[];
  }

  /** Changes one variation in the stored list (jobs write their own variations one at a time). */
  private async setVariant(jobId: string, key: string, change: Partial<MotionVariant>) {
    const job = await this.prisma.mediaJob.findUniqueOrThrow({ where: { id: jobId } });
    const variants = this.variants(job).map((v) => (v.key === key ? { ...v, ...change } : v));
    await this.prisma.mediaJob.update({ where: { id: jobId }, data: { variants: variants as unknown as Prisma.InputJsonValue } });
  }

  private message(error: unknown) {
    const detail = error instanceof Error ? error.message : String(error);
    return this.debug ? `${FRIENDLY} [dev: ${detail.slice(-300)}]` : FRIENDLY;
  }

  /** What to draw: the photo, the business's logo file, and the words. */
  private async request(job: MediaJob, words?: string[]): Promise<MotionRequest> {
    const o = job.options as unknown as MotionOptions;
    const [photo, logo] = await Promise.all([
      this.storage.download(job.inputUrl!),
      o.logoUrl ? this.storage.download(o.logoUrl).catch(() => null) : Promise.resolve(null),
    ]);
    return { photo, logo, words: words ?? o.words, businessName: o.businessName, cta: o.cta ?? undefined, handle: o.handle ?? undefined };
  }

  /** Storyboards first (seconds), then the videos (about 40 s each), so people can start choosing early. */
  private run(job: MediaJob, keys: string[]) {
    void (async () => {
      const userId = job.userId;
      try {
        await this.prisma.mediaJob.update({ where: { id: job.id }, data: { status: 'RUNNING' } });
        const all = this.variants(job).filter((v) => keys.includes(v.key));
        const redoWords = all.length === 1 ? all[0].words : undefined;
        const prepared = await this.motion.prepare(await this.request(job, redoWords));
        for (const v of all) {
          const board = await this.motion.storyboard(prepared, v.template);
          const url = await this.storage.upload(`videos/${userId}/${job.id}-${v.key}-board-${Date.now()}.jpg`, board, 'image/jpeg');
          await this.setVariant(job.id, v.key, { storyboardUrl: url, status: 'RUNNING' });
        }
        for (const v of all) {
          try {
            const mp4 = await this.motion.video(prepared, v.template);
            const url = await this.storage.upload(`videos/${userId}/${job.id}-${v.key}-${Date.now()}.mp4`, mp4, 'video/mp4');
            await this.setVariant(job.id, v.key, { outputUrl: url, status: 'DONE' });
          } catch (error) {
            this.logger.warn(`Motion ${job.id} variation ${v.key} failed: ${error instanceof Error ? error.message : String(error)}`);
            await this.setVariant(job.id, v.key, { status: 'FAILED', error: this.message(error) });
          }
        }
        const done = await this.prisma.mediaJob.findUniqueOrThrow({ where: { id: job.id } });
        const anyDone = this.variants(done).some((v) => v.status === 'DONE');
        await this.prisma.mediaJob.update({ where: { id: job.id }, data: { status: anyDone ? 'DONE' : 'FAILED', error: anyDone ? null : FRIENDLY } });
      } catch (error) {
        this.logger.warn(`Motion ${job.id} failed: ${error instanceof Error ? error.message : String(error)}`);
        const current = await this.prisma.mediaJob.findUnique({ where: { id: job.id } }).catch(() => null);
        if (!current) return;
        const variants = this.variants(current).map((v) => (keys.includes(v.key) && v.status !== 'DONE' ? { ...v, status: 'FAILED' as const, error: this.message(error) } : v));
        const anyDone = variants.some((v) => v.status === 'DONE');
        await this.prisma.mediaJob
          .update({
            where: { id: job.id },
            data: { status: anyDone ? 'DONE' : 'FAILED', error: anyDone ? null : this.message(error), variants: variants as unknown as Prisma.InputJsonValue },
          })
          .catch(() => undefined);
      }
    })();
  }
}
